#!/usr/bin/env node
/* ============================================================
   Build the Travel Marketing Studio as ONE self-contained HTML file.
   ------------------------------------------------------------
   Inlines every asset — CSS, JS, the three woff2 fonts (as base64
   data URIs) and the favicon — so the result opens by double-click
   from disk with no server, no npm install and no network.

   Usage:
     node tools/build-single-file.js [outfile]
     npm run build:standalone

   Default output: travel-marketing-studio.html (repo root)
   ============================================================ */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'public-travelpulse');
const OUT = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(ROOT, 'travel-marketing-studio.html');

const read = (file) => fs.readFileSync(path.join(SRC, file));

const MIME = {
  '.woff2': 'font/woff2',
  '.svg': 'image/svg+xml'
};

function dataUri(file) {
  const ext = path.extname(file).toLowerCase();
  const mime = MIME[ext] || 'application/octet-stream';
  return `data:${mime};base64,${read(file).toString('base64')}`;
}

function kb(n) {
  return `${(n / 1024).toFixed(1)} KB`;
}

/* ---------------- 1. CSS, with the fonts embedded ---------------- */

let css = read('styles.css').toString('utf8');
const fontFiles = [...new Set(css.match(/fonts\/[a-z0-9-]+\.woff2/g) || [])];

for (const file of fontFiles) {
  // Every occurrence of this url() must become the same data URI.
  const encoded = dataUri(file);
  const pattern = new RegExp(`url\\("${file.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"\\)`, 'g');
  css = css.replace(pattern, `url("${encoded}")`);
}

if (/url\(\s*["']?(?!data:)[^)"']+\.(woff2?|ttf|otf|png|jpe?g|gif|svg)/.test(css)) {
  throw new Error('An unresolved asset URL is still present in the CSS');
}

/* ---------------- 2. JS ---------------- */

const scripts = ['content-model.js', 'app.js'].map((file) => {
  const js = read(file).toString('utf8');
  if (/<\/script/i.test(js)) {
    throw new Error(`${file} contains a literal </script> and cannot be inlined`);
  }
  return { file, js };
});

/* ---------------- 3. HTML ---------------- */

let html = read('index.html').toString('utf8');

const styleTag = `<style>\n${css}\n  </style>`;
const scriptTags = scripts
  .map((s) => `  <!-- ${s.file} -->\n  <script>\n${s.js}\n  </script>`)
  .join('\n');

let replacedCss = 0;
html = html.replace(
  /[ \t]*<link\s+rel="stylesheet"\s+href="styles\.css"\s*\/?>/,
  () => (replacedCss++, styleTag)
);

let replacedIcon = 0;
html = html.replace(
  /[ \t]*<link\s+rel="icon"[^>]*>/,
  () => (replacedIcon++, `<link rel="icon" href="${dataUri('favicon.svg')}" />`)
);

let replacedScripts = 0;
html = html.replace(
  /[ \t]*<script\s+src="(content-model|app)\.js"><\/script>\s*/g,
  (match) => (replacedScripts++, '')
);

const closing = html.lastIndexOf('</body>');
if (closing === -1) throw new Error('Could not find </body>');

html = `${html.slice(0, closing)}\n${scriptTags}\n${html.slice(closing)}`;

if (replacedCss !== 1) throw new Error(`Expected 1 stylesheet link, replaced ${replacedCss}`);
if (replacedIcon !== 1) throw new Error(`Expected 1 favicon link, replaced ${replacedIcon}`);
if (replacedScripts !== 2) throw new Error(`Expected 2 script tags, replaced ${replacedScripts}`);

/* A single-file build is opened from disk; point that out at the top. */
html = html.replace(
  '<!DOCTYPE html>',
  `<!DOCTYPE html>\n<!--
  Travel Marketing Studio — single-file build.
  Everything (CSS, JS, three fonts, favicon) is embedded; open it by
  double-click. No server, no npm install, no network required.
  Generated by tools/build-single-file.js — regenerate rather than edit.
-->`
);

/* ---------------- 4. Write ---------------- */

fs.writeFileSync(OUT, html, 'utf8');

const bytes = Buffer.byteLength(html, 'utf8');
console.log('✅ Single-file build written');
console.log(`   ${path.relative(process.cwd(), OUT) || OUT}`);
console.log(`   ${kb(bytes)} total`);
console.log(`   fonts embedded: ${fontFiles.length} (${fontFiles.join(', ')})`);
console.log('   external requests: 0');
